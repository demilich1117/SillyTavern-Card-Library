async (page) => {
    const checks = [];
    const check = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
    await page.goto('http://127.0.0.1:18788/?tt');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: '📚 打开角色书库', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.cl-index-status').textContent.includes('已就绪'));
    check(await page.evaluate(() => document.querySelector('#cl-library').dataset.ttMobileSurface === 'fullscreen-window'), 'TT 就绪分支和移动 surface 标记');
    await page.getByRole('button', { name: '筛选与排序', exact: true }).click();
    await page.getByRole('button', { name: '新建分组', exact: true }).filter({ visible: true }).click();
    await page.getByRole('textbox', { name: '分组名称', exact: true }).fill('手机整理');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    const groupId = await page.evaluate(() => SillyTavern.getContext().extensionSettings.card_library.groups.find(group => group.name === '手机整理').id);
    await page.getByRole('button', { name: '应用', exact: true }).click();
    await page.getByRole('combobox', { name: '选择独立分组' }).selectOption(groupId);
    await page.getByRole('button', { name: '筛选与排序', exact: true }).click();
    await page.getByRole('button', { name: '管理所选分组', exact: true }).click();
    await page.getByRole('textbox', { name: '分组名称', exact: true }).fill('手机改名');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.getByRole('button', { name: '应用', exact: true }).click();
    check(await page.getByRole('combobox', { name: '选择独立分组' }).inputValue() === groupId, '手机直接新建与重命名分组');
    await page.getByRole('combobox', { name: '选择独立分组' }).selectOption('all');
    await page.getByRole('button', { name: '预览 林间的药师', exact: true }).click();
    check(await page.getByRole('button', { name: '返回书库', exact: true }).isVisible() && !await page.getByRole('searchbox', { name: '搜索角色卡', exact: true }).isVisible(), '手机详情替换列表并保留返回');
    await page.getByRole('button', { name: '编辑角色卡', exact: true }).click();
    await page.getByLabel('作者备注', { exact: true }).fill('手机表单保存验证');
    await page.getByRole('button', { name: '保存修改', exact: true }).click();
    await page.waitForFunction(() => !Array.from(document.querySelectorAll('dialog')).some(node => node.getAttribute('aria-label') === '快速编辑角色卡'));
    check((await page.getByRole('tabpanel').innerText()).includes('手机表单保存验证'), '长表单末尾字段可编辑，固定保存按钮可达');
    await page.getByRole('button', { name: '返回书库', exact: true }).click();
    await page.setViewportSize({ width: 320, height: 568 });
    check(await page.evaluate(() => document.querySelector('#cl-library').scrollWidth <= innerWidth && document.querySelector('.cl-main').scrollWidth <= document.querySelector('.cl-main').clientWidth), '320px 无横向溢出');
    await page.getByRole('button', { name: '整理数据与外观', exact: true }).click();
    await page.getByRole('combobox', { name: '外观', exact: true }).selectOption('dark');
    check(await page.evaluate(() => [...document.querySelectorAll('.cl-root')].every(node => node.dataset.theme === 'dark')), '外观立即应用到主窗和弹窗');
    const pendingDownload = page.waitForEvent('download');
    await page.getByRole('button', { name: '导出整理数据', exact: true }).click();
    const file = await pendingDownload;
    await file.saveAs('output/playwright/library-export.json');
    check(file.suggestedFilename().endsWith('.json'), '整理数据导出经由宿主下载函数');
    await page.getByLabel('导入整理数据', { exact: true }).setInputFiles('output/playwright/library-export.json');
    await page.getByRole('button', { name: '合并', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('dialog[open]').length === 1);
    check(await page.evaluate(() => SillyTavern.getContext().extensionSettings.card_library.groups.filter(group => group.name === '手机改名').length === 1), '导入同名分组合并，不制造重复');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: '预览 林间的药师', exact: true }).click();
    await page.getByRole('tab', { name: '人设', exact: true }).focus();
    await page.keyboard.press('ArrowRight');
    check(await page.getByRole('tab', { name: '开场白', exact: true }).getAttribute('aria-selected') === 'true', '预览标签支持方向键');
    await page.getByRole('button', { name: '开始聊天', exact: true }).click();
    check(await page.evaluate(() => !document.querySelector('#cl-library') && SillyTavern.getContext().characters[SillyTavern.getContext().characterId]?.avatar === 'fixture-2.png'), '显式开始聊天才切换角色并关闭书库');
    return { passed: checks.length, checks, nativeTT: false };
}
