async (page) => {
    const checks = [];
    const check = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
    const search = page.getByRole('searchbox', { name: '搜索角色卡', exact: true });
    await search.fill('第三盏灯');
    await page.waitForFunction(() => document.querySelectorAll('.cl-card').length === 1);
    check(await page.getByRole('button', { name: '预览 雾港来信', exact: true }).count() === 1, '跨全库搜索人设，同名卡片仍独立');
    await page.getByRole('button', { name: '预览 雾港来信', exact: true }).click();
    check(await page.evaluate(() => SillyTavern.getContext().characterId === undefined), '预览不切换当前角色');
    await page.getByRole('tab', { name: '开场白', exact: true }).click();
    await page.getByRole('combobox', { name: '选择开场白' }).selectOption('2');
    await page.frameLocator('.cl-opening-frame').getByRole('heading', { name: '蓝色风铃' }).waitFor();
    check(true, '备用开场切换');
    await page.getByRole('tab', { name: '世界书', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.cl-world-title').length === 3);
    check(await page.locator('.cl-world-entry').count() === 3, '内嵌、主世界书、额外世界书都可预览');
    await page.getByRole('tab', { name: '聊天', exact: true }).click();
    await page.locator('.cl-chat-row').first().click();
    await page.getByRole('searchbox', { name: '搜索聊天记录' }).fill('琥珀钥匙');
    check((await page.locator('.cl-messages').innerText()).includes('最早的一条消息'), '完整聊天搜索可找到第 1 条，不限最后 60 条');
    await page.getByRole('button', { name: '关闭预览', exact: true }).click();
    await page.getByRole('button', { name: '编辑角色卡', exact: true }).click();
    await page.getByLabel('主开场白', { exact: true }).fill('修改后的主开场，测试保存且保留其他插件数据。');
    await page.getByRole('button', { name: '保存修改', exact: true }).click();
    await page.waitForFunction(() => !Array.from(document.querySelectorAll('dialog')).some(node => node.getAttribute('aria-label') === '快速编辑角色卡'));
    const saved = await page.evaluate(async () => (await (await fetch('/api/test-state', { method: 'POST' })).json()).cards[0]);
    check(saved.first_mes.startsWith('修改后') && saved.data.first_mes === saved.first_mes && saved.data.extensions.arbitrary_plugin.keep, '编辑保存同步两个表示，保留未知扩展字段');
    await page.getByRole('button', { name: '编辑角色卡', exact: true }).click();
    await page.getByLabel('主开场白', { exact: true }).fill('这条修改应该放弃');
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: '放弃修改', exact: true }).click();
    check(await page.getByRole('dialog', { name: '角色书库', exact: true }).count() === 1, 'Escape 只关闭编辑层，未保存提示可操作');
    await page.getByRole('button', { name: '分组', exact: true }).click();
    await page.getByRole('textbox', { name: '新分组名称', exact: true }).fill('测试整理组');
    await page.getByRole('button', { name: '新建', exact: true }).click();
    await page.getByRole('button', { name: '应用分组', exact: true }).click();
    check(await page.evaluate(() => SillyTavern.getContext().extensionSettings.card_library.groups.some(group => group.name === '测试整理组' && group.members.includes('fixture-1.png'))), '独立分组可创建并应用');
    await page.getByRole('button', { name: 'AI 概括', exact: true }).click();
    await page.getByRole('button', { name: '生成概括', exact: true }).click();
    await page.getByRole('button', { name: '保存修改并按类型分组', exact: true }).click();
    check(await page.evaluate(() => Boolean(SillyTavern.getContext().extensionSettings.card_library.summaries['card:fixture-1.png'])), 'AI 分类结果确认保存（模拟生成）');
    await page.getByRole('button', { name: '返回书库', exact: true }).click();
    await search.fill('紫色鲸鱼');
    await page.waitForFunction(() => document.querySelectorAll('.cl-card').length === 0);
    await page.getByRole('checkbox', { name: '含关联世界书', exact: true }).check();
    await page.waitForFunction(() => document.querySelectorAll('.cl-card').length === 1);
    check(true, '关联世界书开关实际扩展搜索范围');
    await search.fill(''); await page.waitForFunction(() => document.querySelectorAll('.cl-card').length === 8);
    await page.getByRole('button', { name: '预览 很长的角色名：沿着看不见尽头的旅途直到世界的另一端', exact: true }).click();
    check(await page.evaluate(() => !window.cardLibraryXss && document.querySelector('.cl-prose').textContent.includes('<script>')), '恶意 HTML 作为原文显示，不执行');
    await page.getByRole('button', { name: '返回书库', exact: true }).click();
    await page.getByRole('checkbox', { name: '选择 今天也要营业', exact: true }).check();
    await page.getByRole('checkbox', { name: '选择 星图以外', exact: true }).check();
    await page.getByRole('button', { name: '删除', exact: true }).click();
    check(await page.getByRole('button', { name: '删除 2 张', exact: true }).isDisabled(), '批量删除需要输入确认数量');
    check(!await page.getByRole('checkbox', { name: '同时永久删除这些角色的聊天记录' }).isChecked(), '删除默认保留聊天');
    await page.getByLabel('确认删除数量', { exact: true }).fill('2');
    await page.getByRole('button', { name: '删除 2 张', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.cl-card').length === 6);
    const state = await page.evaluate(async () => (await (await fetch('/api/test-state', { method: 'POST' })).json()));
    check(state.counts.requests.filter(item => item.path === '/api/characters/delete').every(item => item.body.delete_chats === false), '批量删除路由保留聊天并核对结果');
    await page.getByRole('button', { name: '关闭书库', exact: true }).click();
    await page.reload(); await page.getByRole('button', { name: '📚 打开角色书库', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.cl-index-status').textContent.includes('已就绪'));
    check(await page.evaluate(() => SillyTavern.getContext().extensionSettings.card_library.groups.some(group => group.name === '测试整理组')), '刷新后整理数据仍存在');
    check(await page.evaluate(() => document.querySelectorAll('#cl-menu-entry').length === 1), '初始化入口无重复');
    return { passed: checks.length, checks };
}
